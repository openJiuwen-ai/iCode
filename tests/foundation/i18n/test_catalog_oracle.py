"""Live catalog oracle: the tracked POT and PO, and the generated MO, carry exactly the pinned message ids and load."""

from __future__ import annotations

import gettext
import subprocess
from pathlib import Path

import pytest
from scripts import i18n, i18n_mo

from chrys.foundation.i18n.catalogs import load_catalog
from tests.foundation.i18n._catalog_helpers import (
    _assert_po_mo_semantically_consistent,
    _effective_catalog_entries,
    _entry_id,
    _read_catalog,
)
from tests.foundation.i18n._catalog_oracle_ids import EXPECTED_MESSAGE_IDS
from tests.support.ci import CI_LINUX_ONLY

_STALE_MO_HINT = (
    "the generated zh-Hans MO is missing or stale: run `uv run python scripts/i18n.py compile` "
    "or `uv sync --reinstall-package icode-tui` (uv may not rebuild it on its own after `git clean`)"
)


@CI_LINUX_ONLY
def test_live_catalog_artifacts_contain_effective_translations_and_are_loadable() -> None:
    pot = _read_catalog(i18n.POT_PATH)
    po = _read_catalog(i18n.ZH_PO_PATH)

    assert {_entry_id(message) for message in pot if message.id} == EXPECTED_MESSAGE_IDS
    assert {_entry_id(message) for message in po if message.id} == EXPECTED_MESSAGE_IDS
    assert set(_effective_catalog_entries(po)) == EXPECTED_MESSAGE_IDS
    assert po.num_plurals == 1
    assert po.plural_expr == "0"
    assert i18n.ZH_MO_PATH.is_file(), _STALE_MO_HINT
    with i18n.ZH_MO_PATH.open("rb") as stream:
        translations = gettext.GNUTranslations(stream)
    assert translations.gettext("missing.key") == "missing.key"
    assert "nplurals=1" in translations.info()["plural-forms"]
    assert not (i18n.REPO_ROOT / "locales" / "en" / "LC_MESSAGES" / "chrys.po").exists()
    assert not (i18n.REPO_ROOT / "locales" / "en" / "LC_MESSAGES" / "chrys.mo").exists()
    _assert_po_mo_semantically_consistent(
        source_root=i18n.SOURCE_ROOT,
        pot_path=i18n.POT_PATH,
        po_path=i18n.ZH_PO_PATH,
        mo_path=i18n.ZH_MO_PATH,
    )


def test_installed_package_serves_the_catalog_compiled_from_the_current_po(tmp_path: Path) -> None:
    # Not CI_LINUX_ONLY: the MO is generated by the editable build on every OS,
    # including when CI restores a cached virtualenv onto a fresh checkout.
    # The compiler is deterministic, so a byte match proves the copy is fresh.
    fresh = tmp_path / "chrys.mo"
    i18n_mo.compile_mo(i18n.ZH_PO_PATH, fresh)
    assert i18n.ZH_MO_PATH.is_file(), _STALE_MO_HINT
    assert i18n.ZH_MO_PATH.read_bytes() == fresh.read_bytes(), _STALE_MO_HINT
    assert load_catalog("zh-Hans").gettext("tui.theme_editor.cancel") == "取消"


@CI_LINUX_ONLY
def test_the_generated_catalog_is_never_tracked() -> None:
    # A branch that tracked the MO before it became generated meets a
    # modify/delete conflict on merge; resolving it with `git add` would bring
    # back the binary file every translating branch conflicts on.
    listed = subprocess.run(
        ["git", "ls-files", "--", "src/chrys/foundation/i18n/_catalogs"],
        cwd=i18n.REPO_ROOT,
        capture_output=True,
        encoding="utf-8",
        stdin=subprocess.DEVNULL,
        check=False,
    )
    if listed.returncode != 0:
        pytest.skip(f"not a Git checkout: {listed.stderr.strip()}")
    assert listed.stdout.split() == [], "remove the compiled catalog from Git: `git rm --cached <path>`"
