@dataclass(frozen=True, slots=True)
class SharedRuntime:
    """Only Prepared-lifetime dependencies; no session-bound tool providers."""

    client: BaseChatClient
    tools: list[Any]
    providers: list[Any]
    name: str
    instructions: str
    vision: bool


@dataclass(frozen=True, slots=True)
class MainRecipe:
    """Root context/usage before injection, image, reminder, validation."""

    context: ContextInputs
    reminder: ReminderInputs
    last_words: LastWordsInputs
    injection: Callable[[], InjectionMiddleware]
    validation: Callable[[Conversation], ResponseValidationMiddleware]
    persist_recovery: Callable[[], Awaitable[bool]] | None


@dataclass(frozen=True, slots=True)
class ChildRecipe:
    """Private child context; image/reminder precede run usage/validation.

    Registration's unused template keeps its historical usage middleware;
    invocation wrappers never enter the shared client's context manager.
    """

    context: ContextInputs
    reminder: ReminderInputs
    last_words: LastWordsInputs
    registration: bool


@dataclass(slots=True)
class KernelRuntime:
    """The state owned by one conversation; the Agent borrows shared transport."""

    owner: Conversation
    agent: Agent
    context: ContextManager
    reminder: SystemReminderMiddleware
    last_words: LastWordsState
    injection: InjectionMiddleware | None = None
    validation: ResponseValidationMiddleware | None = None

    def create_session(self) -> AgentSession:
        return self.agent.create_session()


def create_context(inputs: ContextInputs) -> ContextManager:
    return ContextManager(**inputs)


def create_reminder(inputs: ReminderInputs) -> tuple[SystemReminderMiddleware, LastWordsState]:
    """Build the reminder middleware and the LAST_WORDS state it renders, on one shared turn holder."""
    turns = ReminderTurns()
    last_words = LastWordsState(
        turns,
        spill_quota=inputs.get("spill_quota"),
        session_root=inputs.get("session_root"),
        file_read_available=inputs.get("file_read_available", False),
        todo_provider=inputs.get("todo_state_provider"),
    )
    return SystemReminderMiddleware(**inputs, last_words=last_words), last_words


def restore_phase4_state(
    reminder: SystemReminderMiddleware,
    last_words: LastWordsState,
    state: Mapping[str, Any] | None,
    *,
    available_relative_paths: frozenset[str] | set[str] | None = None,
) -> None:
    """Restore persisted Phase 4 state: the LAST_WORDS slot and the catalog pointer's record count."""
    if not reminder.renders_last_words(last_words):
        raise ValueError("restore_phase4_state needs the LAST_WORDS state this reminder middleware renders")
    state = state or {}
    last_words.restore(state, available_relative_paths=available_relative_paths)
    reminder.sources.archive_pointer.restore_record_count(state.get(CATALOG_POINTER_RECORD_COUNT_STATE_KEY))


def create_runtime(
    owner: Conversation,
    shared: SharedRuntime,
    recipe: MainRecipe | ChildRecipe,
    *,
    context: ContextManager | None = None,
    injection: InjectionMiddleware | None = None,
) -> KernelRuntime:
    """Assemble fresh mutable runtime, preserving both established chat chains.

    Main build prepares context before tool/skill progress, then completes it
    here. Child opens construct context here, after the invocation skill refresh.
    When context is supplied, recipe.context is not used to create a context.
    """
    ctx = create_context(recipe.context) if context is None else context
    reminder, last_words = create_reminder(recipe.reminder)
    ctx.compaction_strategy.bind_reminder(reminder, last_words)
    if isinstance(recipe, MainRecipe) and recipe.persist_recovery is not None:
        ctx.compaction_strategy.set_recovery_persistence_callback(recipe.persist_recovery)
    generator = LastWordsGenerator(**recipe.last_words)
    owner.own(generator.aclose)
    ctx.compaction_strategy.set_last_words_generator(generator)
    validation = recipe.validation(owner) if isinstance(recipe, MainRecipe) else None
    if isinstance(recipe, MainRecipe):
        injection = owner.retain(recipe.injection() if injection is None else injection)
        injection.set_on_drained_reminders(reminder.queue_drained_injection_reminders)
    chain: list[ChatMiddleware] = []
    if isinstance(recipe, MainRecipe):
        chain.extend(ctx.middleware)
        if injection is None:
            raise RuntimeError("The main agent recipe requires injection middleware.")
        chain.append(injection)
    elif recipe.registration:
        chain.extend(ctx.middleware)
    chain.append(image_stub_middleware_for_model(vision_enabled=shared.vision))
    chain.append(reminder)
    if isinstance(recipe, MainRecipe):
        if validation is None:
            raise RuntimeError("The main agent recipe requires response validation middleware.")
        chain.append(validation)
    agent = Agent(
        client=shared.client,
        name=shared.name,
        instructions=shared.instructions,
        tools=list(shared.tools),
        context_providers=[*ctx.providers, *shared.providers],
        middleware=chain,
    )
    return owner.retain(
        KernelRuntime(
            owner=owner,
            agent=agent,
            context=ctx,
            reminder=reminder,
            last_words=last_words,
            injection=injection,
            validation=validation,
        )
    )


async def create_approval(owner: Conversation, inputs: ApprovalInputs) -> ApprovalMiddleware:
    approval = ApprovalMiddleware(**inputs)
    await owner.own_or_release(approval.close)
    return approval


def create_ask_user(owner: Conversation, inputs: AskUserInputs) -> AskUserMiddleware:
    return owner.retain(AskUserMiddleware(**inputs))


def create_validation(
    owner: Conversation, *, publish_retry: Callable[[RetryAttemptInfo], Awaitable[None]] | None
) -> ResponseValidationMiddleware:
    return owner.retain(ResponseValidationMiddleware(publish_retry=publish_retry))
