@dataclass(frozen=True)
class InputRestore:
    """Proof that one specific restore put its text into an empty composer.

    Handed out by :meth:`restore_input_text` and redeemable exactly once, by
    :meth:`rewrite_restored_input`, for a follow-up that rewrites *that* text
    in place. Ownership is the credential, never text equality across
    operations: a draft the user typed — or retyped — is never ours to
    replace, however it happens to read.
    """

    generation: int
    text: str


