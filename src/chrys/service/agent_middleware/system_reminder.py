"""SystemReminderMiddleware — injects ``<system-reminder>`` tags per LLM call.

A ``ChatMiddleware`` that fires before each LLM call in the tool loop.
It replaces user messages in ``context.messages`` (a per-call shallow copy)
with enriched versions whose original user contents come first, followed by
``<system-reminder>`` tags.  What each reminder says, and the state behind
it, lives in its source (``reminders/``); this module decides when each one
is sent, records it and fixes the send order.

Reminders stay where they were first sent.  Once a request carrying them is
established, the reminders a user message received are recorded in its
``additional_properties`` (``HistoryMarkerKind.SYSTEM_REMINDERS_KEY``), and
every later call re-renders that record byte-identically — in later turns
too — so the conversation prefix, and the provider's prompt cache over it,
survives from one turn to the next.  The message's own contents never hold a
reminder: ``ChatContext.messages`` is a **shallow copy** of the tool loop's
``prepped_messages``, so enrichment replaces list elements, never the history
message objects.

Only reminders not already visible are added to the last user message:

- the turn line (turn-start time, previous-turn context usage) once per
  turn;
- event reminders (hooks, workspace file changes, the context-usage warning,
  which ``reminders.context_usage`` arms) once per turn by text;
- the profile-switch notice while the latest switch notice the turn shows
  differs — a switch made before a retry reaches the retried request, and
  Code → QA → Code → QA across retries sends the last notice again;
- catalogs — standing context: runtime environment, sub-agent tip, todo
  list, background commands, skill catalog, MCP server instructions, the
  agent's extension contexts, archive-catalog pointer —
  whenever the latest version of that catalog in view differs: a changed
  catalog (changed back included), or one whose carrier a context fold took
  out of view, is sent again, and one no longer offered is replaced by a
  notice that it no longer applies where it has one.

Extension contexts are async, so ``prepare_turn()`` cannot ask them: the
caller that starts a turn awaits ``refresh_extension_context()`` right after
it, and a retry that preserves the turn's reminders keeps their text.

A call that continues a service-side conversation (``conversation_id``)
sends only the new messages, so what that conversation holds is out of view:
the catalogs the last answered call left in it count as in view when the
next call continues exactly from the handle that answer returned.  Any other
handle, a failed call, or a fresh middleware sends them again.

A continuation poll adds and records nothing: the provider ignores its
messages.

Turn reminders are snapshotted at ``prepare_turn()`` and reused for every LLM
call in that turn.  User-initiated injection/retry may refresh the skill
catalog before the next model call because a newly added skill is a
meaningful runtime capability change.  LAST_WORDS is different: it is
generated by mid-turn compaction, remains dynamic and is never recorded.  Do
not reintroduce per-call timestamps or other volatile reminder text.

Escaping scope: this middleware defangs ``<system-reminder>`` tags in
user-role message content only.  Tool-result content (web fetches, file
reads, sub-agent output) is passed through verbatim — treat reminder-shaped
text in tool results as untrusted in downstream prompts and rely on the
model's own judgement, not on this middleware, to discount it.
"""

