REMINDER_TAG_OPEN = "<system-reminder>"
REMINDER_TAG_CLOSE = "</system-reminder>"
ESCAPED_REMINDER_TAG_OPEN = "&lt;system-reminder&gt;"
ESCAPED_REMINDER_TAG_CLOSE = "&lt;/system-reminder&gt;"

LAST_WORDS_PREFIX = "[LAST_WORDS] "
"""Opens every LAST_WORDS block (rendered by ``compaction.last_words_state``).

Load-bearing: ``refresh_last_words_reminder`` finds the blocks to replace by
it, so it must stay byte-identical."""


def escape_system_reminder_tags(text: str) -> str:
    """Defang user-authored reminder tags before text reaches the model."""
    return text.replace(REMINDER_TAG_OPEN, ESCAPED_REMINDER_TAG_OPEN).replace(
        REMINDER_TAG_CLOSE,
        ESCAPED_REMINDER_TAG_CLOSE,
    )


def wrap_system_reminder(content: str) -> str:
    """Wrap *content* in ``<system-reminder>`` tags."""
    return f"{REMINDER_TAG_OPEN}\n{escape_system_reminder_tags(content)}\n{REMINDER_TAG_CLOSE}"


_ReminderKind = Literal["turn", "event", "switch", "catalog"]
_REMINDER_KINDS: frozenset[str] = frozenset(get_args(_ReminderKind))


@dataclass(frozen=True, slots=True)
class _ReminderItem:
    """One reminder text and the rule that decides whether it is sent again.

    ``turn``: turn-start snapshot, sent once per turn as a group.  ``event``:
    sent once per turn per text.  ``switch``: the profile-switch notice, sent
    while the turn's latest switch notice differs.  ``catalog``: standing
    context, sent while the latest version of the catalog *name* in view
    differs.  Records written before the runtime environment, todo list and
    archive pointer became catalogs hold them as ``turn`` items.
    """

    kind: _ReminderKind
    text: str
    name: str | None = None
    """Which catalog a ``catalog`` item is a version of; None for other kinds."""

    def to_record(self) -> dict[str, str]:
        record = {"kind": self.kind, "text": self.text}
        if self.name is not None:
            record["name"] = self.name
        return record


def _recorded_reminders(properties: Mapping[str, Any]) -> list[_ReminderItem]:
    """Return the reminders recorded on a user message, skipping malformed entries."""
    raw = properties.get(HistoryMarkerKind.SYSTEM_REMINDERS_KEY)
    if not isinstance(raw, list):
        return []
    items: list[_ReminderItem] = []
    for entry in raw:
        if not isinstance(entry, Mapping):
            continue
        kind = entry.get("kind")
        text = entry.get("text")
        name = entry.get("name")
        # Type checks first: a persisted list or object ``kind`` is unhashable.
        if isinstance(kind, str) and kind in _REMINDER_KINDS and isinstance(text, str) and text:
            items.append(_ReminderItem(cast("_ReminderKind", kind), text, name if isinstance(name, str) else None))
    return items


def _records_of(messages: Sequence[Message]) -> list[list[_ReminderItem]]:
    """Each message's recorded reminders, parsed once per call (none for non-user roles)."""
    return [
        _recorded_reminders(message.additional_properties) if message.role == "user" else [] for message in messages
    ]


def _record_reminders(properties: dict[str, Any], items: Sequence[_ReminderItem]) -> None:
    """Record *items* on a message, always as a new list.

    Retry rollback restores a props dict from a one-level copy that shares
    its list values, so the stored list itself is never mutated.
    """
    properties[HistoryMarkerKind.SYSTEM_REMINDERS_KEY] = [item.to_record() for item in items]


def _is_visible(message: Message) -> bool:
    return not message.additional_properties.get(EXCLUDED_KEY, False)


def _catalog_key(item: _ReminderItem) -> str:
    """The catalog *item* is a version of; an unnamed entry is its own catalog."""
    return item.name if item.name is not None else item.text


def _latest_switch_notice(items: Iterable[_ReminderItem]) -> str | None:
    """The last profile-switch notice among *items*, if any."""
    latest: str | None = None
    for item in items:
        if item.kind == "switch":
            latest = item.text
    return latest


def _latest_visible_catalogs(
    messages: Sequence[Message],
    records: Sequence[Sequence[_ReminderItem]],
) -> dict[str, str]:
    """The latest version of each catalog recorded on user messages still in view.

    An older version stays in view after a newer one was sent, so a catalog
    compares with its latest version only: A → B → A must send A again.
    """
    latest: dict[str, str] = {}
    for message, items in zip(messages, records, strict=True):
        if message.role != "user" or not _is_visible(message):
            continue
        for item in items:
            if item.kind == "catalog":
                latest[_catalog_key(item)] = item.text
    return latest


def _withdrawn_notices(sources: Iterable[CatalogSource]) -> dict[str, str]:
    """Each catalog's withdrawal notice by record name, for the catalogs that have one.

    A catalog that disappeared (its provider went away or has nothing to say)
    still shows its last version on an earlier message, so the model is told
    it no longer applies.
    """
    return {source.name: source.withdrawn for source in sources if source.withdrawn is not None}


def _catalog_updates(
    latest: Mapping[str, str],
    current: Sequence[_ReminderItem],
    withdrawn_notices: Mapping[str, str],
) -> list[_ReminderItem]:
    """The catalogs to send so that the latest version of each in view is current.

    A changed catalog (changed back included) goes out again; one no longer
    offered is replaced by its notice in *withdrawn_notices* while an older
    version of it is still in view.
    """
    updates = [item for item in current if latest.get(_catalog_key(item)) != item.text]
    offered = {_catalog_key(item) for item in current}
    for name, text in latest.items():
        withdrawn = withdrawn_notices.get(name) or extension_withdrawn_notice(name)
        if name not in offered and withdrawn is not None and text != withdrawn:
            updates.append(_ReminderItem("catalog", withdrawn, name))
    return updates


def _is_continuation_poll(context: ChatContext) -> bool:
    """A poll retrieves an already-created response; the provider ignores its messages."""
    options = context.options
    return options is not None and options.get("continuation_token") is not None


def _service_handle(conversation_id: object) -> str | None:
    """*conversation_id* when it names a service-side conversation."""
    if isinstance(conversation_id, str) and conversation_id and not is_local_history_conversation_id(conversation_id):
        return conversation_id
    return None


@dataclass
class TurnReminderState:
    """Intentionally mutable reminder state shared across one logical turn.

    ContextVar values are copied into child tasks, so the middleware stores one
    state object and mutates it in place.  That lets Phase 4 LAST_WORDS updates
    made inside an agent child task remain visible to sibling retry/resume tasks
    that continue the same logical turn.
    """

    turn_reminders: tuple[str, ...] = ()
    """Turn-start snapshot sent once per turn: time and previous-turn usage."""
    context_warning: str | None = None
    """The context-usage warning, when this turn crosses the threshold."""
    event_reminders: tuple[str, ...] = ()
    """Hook and skill-reference reminders queued for this turn."""
    runtime_hint: str | None = None
    sub_agent_tip: str | None = None
    todo: str | None = None
    """Turn-start todo list (None when empty)."""
    background_tasks: str | None = None
    """Turn-start background commands of the main agent (None when it never had any)."""
    skill_catalog: str | None = None
    mcp_instructions: str | None = None
    extension_catalogs: tuple[tuple[str, str], ...] | None = None
    """``(catalog name, text)`` per extension context that gave text this turn; None until asked."""
    switch: SwitchSnapshot | None = None
    """The switch this turn announces, with its notice: a retry keeps the
    opener's turn group, and the notice must still reach the retried request."""
    file_change: FileChangeTurn | None = None
    """The workspace file-change notice drained for this turn."""
    last_words: LastWordsTurn | None = None
    """The Phase 4 slot ``compaction.last_words_state.LastWordsState`` owns; None until it writes one."""


class LastWordsPort(Protocol):
    """The LAST_WORDS state this middleware renders (``compaction.last_words_state.LastWordsState``)."""

    @property
    def turns(self) -> ReminderTurns:
        """The turn holder the state reads and writes; the middleware keeps its turns there too."""
        ...

    def begin_turn(self, previous: TurnReminderState | None, *, preserve: bool) -> LastWordsTurn:
        """The new turn's LAST_WORDS slot, given the previous turn's container."""
        ...

    def discard_restored(self) -> None:
        """Drop the restored stash: the turn ``begin_turn`` just built took it or discarded it."""
        ...

    def record_paths(self, turn: LastWordsTurn) -> set[str]:
        """The record paths *turn*'s manifest lists."""
        ...

    def render(self) -> list[str]:
        """The LAST_WORDS blocks the next call appends, unwrapped."""
        ...


class ReminderTurns:
    """Where one middleware keeps its per-turn reminder container.

    The container lives in a ContextVar, so a task sees the turn its caller
    prepared, and in an active-turn fallback: the engine runs one main turn
    per middleware at a time, and a child or sibling task started under an
    empty context recovers that turn's container from it.
    """

    def __init__(self) -> None:
        self._local: ContextVar[TurnReminderState | None] = ContextVar(
            f"chrys_reminder_turns_{id(self)}",
            default=None,
        )
        self._active: TurnReminderState | None = None

    @property
    def active(self) -> TurnReminderState | None:
        """The prepared turn's container, in any task."""
        return self._active

    def local(self) -> TurnReminderState | None:
        """This task's container, without the active-turn fallback."""
        return self._local.get()

    def current(self) -> TurnReminderState | None:
        """This task's container, else the active turn's."""
        return self._local.get() or self._active

    def ensure(self) -> TurnReminderState:
        """The current container, or a new empty one for this task only."""
        state = self.current()
        if state is None:
            state = TurnReminderState()
            self._local.set(state)
        return state

    def install(self, state: TurnReminderState) -> None:
        """Make *state* this task's container and the active turn's."""
        self._local.set(state)
        self._active = state

    def install_local(self, state: TurnReminderState) -> None:
        """Make *state* this task's container only."""
        self._local.set(state)

    def clear(self) -> None:
        """Forget the active turn and this task's container."""
        self._local.set(None)
        self._active = None


@dataclass(frozen=True, eq=False)
class CurrentRunReminderScope:
    """Opaque service-owned token for one logical main-agent run."""

    scope_id: int


@dataclass(frozen=True, eq=False)
class CurrentRunReminderTarget:
    """Opaque service-owned current-run reminder target captured by orchestration."""

    scope: CurrentRunReminderScope
    phase: Literal["pre_prepare", "prepared"]
    generation: int
    state: TurnReminderState | None = None


class SystemReminderMiddleware(ChatMiddleware):
    """Appends trailing ``<system-reminder>`` content before each LLM call.

    Each LLM call in the tool loop sees fresh enriched user messages whose
    original user contents come first, followed by the reminders each one
    carried when first sent; the last user message also gets the reminders
    not yet in view.  Exact reserved reminder tags in user-role text are
    escaped in the per-call ``ChatContext.messages`` copy; tool results are
    passed through unchanged.  Message contents in ``prepped_messages`` and
    session state are never modified — only the reminder record in a user
    message's ``additional_properties``.
    """

    def __init__(
        self,
        runtime: SessionEnvironment | None = None,
        *,
        max_context_tokens: int = DEFAULT_MAX_CONTEXT_TOKENS,
        warn_threshold_pct: float = 0.50,
        sub_agent_names: list[str] | None = None,
        shell_tool_enabled: bool = False,
        tool_names: list[str] | None = None,
        session_root: Path | None = None,
        file_read_available: bool = False,
        spill_quota: SpillQuota | None = None,
        catalog_pointer_enabled: bool = True,
        skill_catalog_provider: Callable[[], str | None] | None = None,
        todo_state_provider: Callable[[], str | None] | None = None,
        background_tasks_provider: Callable[[], str | None] | None = None,
        mcp_instructions_provider: Callable[[], str | None] | None = None,
        file_change_provider: Callable[[], str | None] | None = None,
        extension_contexts: Sequence[BoundContext] = (),
        last_words: LastWordsPort | None = None,
    ) -> None:
        """*last_words* comes from ``create_reminder``; the middleware keeps its turns on the state's holder.

        Without *last_words* the middleware renders no LAST_WORDS block and
        cannot be bound to a compaction strategy.
        """
        self._sources = build_sources(
            runtime=runtime,
            max_context_tokens=max_context_tokens,
            warn_threshold_pct=warn_threshold_pct,
            shell_tool_enabled=shell_tool_enabled,
            sub_agent_names=sub_agent_names,
            todo_state_provider=todo_state_provider,
            background_tasks_provider=background_tasks_provider,
            skill_catalog_provider=skill_catalog_provider,
            mcp_instructions_provider=mcp_instructions_provider,
            file_change_provider=file_change_provider,
            tool_names=tool_names,
            session_root=session_root,
            file_read_available=file_read_available,
            spill_quota=spill_quota,
            catalog_pointer_enabled=catalog_pointer_enabled,
            extension_contexts=extension_contexts,
        )
        sources = self._sources
        self._withdrawn_notices = _withdrawn_notices(
            (
                sources.runtime_env,
                sources.sub_agents,
                sources.todo,
                sources.background_tasks,
                sources.skills,
                sources.mcp,
            )
        )
        # The catalogs a service-side conversation holds, keyed by the handle
        # its last answered call returned (see the module docstring).
        self._held_catalogs: tuple[str, dict[str, str]] | None = None
        self._pending_hook_reminders: list[str] = []
        self._next_current_run_scope_id = 1
        self._current_run_scopes: set[CurrentRunReminderScope] = set()
        self._pending_current_run_hook_reminders: dict[CurrentRunReminderScope, list[str]] = {}
        self._active_turn_scope: CurrentRunReminderScope | None = None
        self._current_run_reminder_generation = 0
        # One holder for both, so the note Phase 4 writes is in the container
        # prepare_turn installs.
        self._turns = last_words.turns if last_words is not None else ReminderTurns()
        self._last_words = last_words

    @property
    def sources(self) -> ReminderSources:
        """The content sources this middleware composes; callers reach the switch through it."""
        return self._sources

    def prepare_turn(
        self,
        *,
        reminder_scope: CurrentRunReminderScope | None = None,
        usage: Mapping[str, Any] | None = None,
        preserve_last_words: bool = False,
        preserve_turn_reminders: bool = False,
    ) -> None:
        """Prepare reminder state before ``executor.run()`` or retry/resume.

        ``preserve_last_words`` carries Phase 4 progress across retries.
        ``preserve_turn_reminders`` keeps runtime/usage/switch text
        byte-identical for KV-cache continuity on retry.
        """
        previous = self._turns.current()
        snapshot_catalog_pointer = False
        if preserve_turn_reminders and previous is not None:
            snapshot = TurnReminderState(
                turn_reminders=previous.turn_reminders,
                context_warning=previous.context_warning,
                event_reminders=previous.event_reminders,
                runtime_hint=previous.runtime_hint,
                sub_agent_tip=previous.sub_agent_tip,
                todo=previous.todo,
                background_tasks=previous.background_tasks,
                skill_catalog=previous.skill_catalog,
                mcp_instructions=previous.mcp_instructions,
                extension_catalogs=previous.extension_catalogs,
                switch=previous.switch,
            )
        else:
            snapshot = self._snapshot_turn_reminders(usage=usage or {})
            snapshot.skill_catalog = self._sources.skills.snapshot()
            snapshot.mcp_instructions = self._sources.mcp.snapshot()
            snapshot_catalog_pointer = True
        event_reminders = snapshot.event_reminders
        self._current_run_reminder_generation += 1
        if reminder_scope is not None:
            scoped_reminders = self._pending_current_run_hook_reminders.pop(reminder_scope, [])
            if scoped_reminders:
                event_reminders = (*event_reminders, *scoped_reminders)
        if self._pending_hook_reminders:
            event_reminders = (*event_reminders, *self._pending_hook_reminders)
            self._pending_hook_reminders.clear()
        last_words = (
            self._last_words.begin_turn(previous, preserve=preserve_last_words)
            if self._last_words is not None
            else None
        )
        pointer = self._sources.archive_pointer
        if snapshot_catalog_pointer:
            restored_pointer_count = pointer.restored_record_count if preserve_last_words and previous is None else None
            if restored_pointer_count is not None:
                pointer.capture(restored_pointer_count)
            else:
                # Legacy restored sessions did not persist the turn-start
                # snapshot. Excluding the bounded active manifest is the best
                # compatible approximation, but new saves never rely on it.
                active_manifest_paths = (
                    self._last_words.record_paths(last_words)
                    if self._last_words is not None and last_words is not None
                    else set()
                )
                pointer.capture_live(excluded_relative_paths=active_manifest_paths)
        # The restored stashes are single-shot either way: a preserving turn
        # consumed them; a fresh turn discards them (matching the in-process
        # new-turn semantics).
        pointer.discard_restored()
        if self._last_words is not None:
            self._last_words.discard_restored()
        state = replace(
            snapshot,
            event_reminders=event_reminders,
            file_change=self._sources.file_change.drain(),
            last_words=last_words,
        )
        self._turns.install(state)
        self._active_turn_scope = reminder_scope
        self._sources.profile_switch.begin_turn()

    def take_undelivered_file_change(self) -> str | None:
        """Pop the prepared notice unless a model-bound request already carried it."""
        state = self._turns.current()
        if state is None:
            return None
        notice = state.file_change
        state.file_change = None
        if notice is None or notice.delivered:
            return None
        return notice.text

    def create_current_run_scope(self) -> CurrentRunReminderScope:
        """Allocate a service-owned reminder scope for a logical main-agent run."""
        scope = CurrentRunReminderScope(self._next_current_run_scope_id)
        self._next_current_run_scope_id += 1
        self._current_run_scopes.add(scope)
        return scope

    def capture_current_run_target(
        self,
        reminder_scope: CurrentRunReminderScope,
    ) -> CurrentRunReminderTarget | None:
        """Capture a current-run reminder target if *reminder_scope* is still valid."""
        if reminder_scope not in self._current_run_scopes:
            return None
        active = self._turns.active
        if self._active_turn_scope is reminder_scope and active is not None:
            return CurrentRunReminderTarget(
                scope=reminder_scope,
                phase="prepared",
                generation=self._current_run_reminder_generation,
                state=active,
            )
        return CurrentRunReminderTarget(
            scope=reminder_scope,
            phase="pre_prepare",
            generation=self._current_run_reminder_generation,
        )

    def queue_hook_reminders_for_current_run(
        self,
        target: CurrentRunReminderTarget,
        reminders: list[str],
    ) -> bool:
        """Queue hook reminders only if the captured current-run target is still valid."""
        if not self._is_current_run_target_valid(target):
            return False
        clean = [reminder for reminder in reminders if reminder]
        if not clean:
            return True
        if target.phase == "prepared" and target.state is not None:
            target.state.event_reminders = (*target.state.event_reminders, *clean)
            return True
        active = self._turns.active
        if self._active_turn_scope is target.scope and active is not None:
            active.event_reminders = (*active.event_reminders, *clean)
            return True
        self._pending_current_run_hook_reminders.setdefault(target.scope, []).extend(clean)
        return True

    def update_skill_catalog_for_current_run(self, target: CurrentRunReminderTarget) -> bool:
        """Refresh the skill catalog only if the captured current-run target is current."""
        if not self._is_current_run_target_valid(target):
            return False
        active = self._turns.active
        if target.phase == "prepared" and target.state is not None:
            target.state.skill_catalog = self._sources.skills.snapshot()
        elif self._active_turn_scope is target.scope and active is not None:
            active.skill_catalog = self._sources.skills.snapshot()
        return True

    def set_skill_catalog_for_current_run(
        self,
        target: CurrentRunReminderTarget,
        skill_catalog: str | None,
    ) -> bool:
        """Set the skill catalog only if the captured current-run target is current."""
        if not self._is_current_run_target_valid(target):
            return False
        active = self._turns.active
        if target.phase == "prepared" and target.state is not None:
            target.state.skill_catalog = skill_catalog
        elif self._active_turn_scope is target.scope and active is not None:
            active.skill_catalog = skill_catalog
        return True

    def is_current_run_target_valid(self, target: CurrentRunReminderTarget) -> bool:
        """Return whether a captured current-run reminder target is still valid."""
        return self._is_current_run_target_valid(target)

    def expire_current_run_scope(self, reminder_scope: CurrentRunReminderScope) -> None:
        """Expire a current-run scope and discard stale reminders for it."""
        self._current_run_scopes.discard(reminder_scope)
        self._pending_current_run_hook_reminders.pop(reminder_scope, None)
        if self._active_turn_scope is reminder_scope:
            self._active_turn_scope = None
            self._turns.clear()

    def renders_last_words(self, state: object) -> bool:
        """Whether *state* is the LAST_WORDS state this middleware renders."""
        return self._last_words is not None and self._last_words is state

    def refresh_last_words_reminder(self, messages: list[Any]) -> int | None:
        """Rewrite the ``[LAST_WORDS]`` reminder on a per-call message list.

        Phase 4 compaction runs *below* this middleware (inside the client's
        message prep), so the LLM call that triggered it was enriched before
        the new note existed — without this refresh, that call would go out
        with its tool-call history dropped but only a stale note (or none)
        in its place, and the model would restart the task from scratch.

        Rebuilds the last user message with the current note rendered
        exactly as the next call's enrichment will render it, keeping the
        request prefix byte-stable across calls.  The list entry is
        *replaced* with a fresh ``Message`` — the existing object is never
        mutated, because when enrichment was skipped it is the live history
        message.  ``additional_properties`` is shared by reference so
        exclusion flags keep writing through to the history object; the
        caller must recompute any token annotation riding in it, since the
        shared count still describes the pre-refresh contents.  Returns the
        index of the replaced entry, or ``None`` when the list was left
        unmodified.
        """
        message, idx = self._find_user_message(messages)
        if message is None:
            return None
        reminders = self._last_words_reminders()
        kept = [c for c in message.contents if not self._is_last_words_reminder_content(c)]
        if len(kept) == len(message.contents) and not reminders:
            return None
        messages[idx] = self._rebuild(message, [*kept, *(wrap_system_reminder(r) for r in reminders)])
        return idx

    def restore_folded_reminders(self, messages: list[Message]) -> int | None:
        """Re-send catalogs (standing context) a context fold just took out of view on this call.

        A catalog is sent once and then only re-rendered from the user
        message that recorded it.  Folds (``compress_context``, Phase 3) run
        *below* this middleware, inside the client's message prep, and
        exclude whole earlier turns: when the carrier goes, the call that
        triggered the fold would otherwise go out without the catalog.  The
        missing catalogs are appended to the last user message, before any
        LAST_WORDS block, and recorded on it, so later calls and turns render
        them there.

        The list entry is replaced with a fresh ``Message`` sharing the
        original's ``additional_properties``, as ``refresh_last_words_reminder``
        does; the caller must recompute token annotations from the returned
        index.  Returns ``None`` when nothing was missing.
        """
        message, idx = self._find_user_message(messages)
        state = self._turns.current()
        if message is None or state is None or not _is_visible(message):
            return None
        missing = _catalog_updates(
            _latest_visible_catalogs(messages, self._rendered_records(messages)),
            self._catalog_items(state),
            self._withdrawn_notices,
        )
        if not missing:
            return None
        kept = [c for c in message.contents if not self._is_last_words_reminder_content(c)]
        last_words = [c for c in message.contents if self._is_last_words_reminder_content(c)]
        messages[idx] = self._rebuild(
            message, [*kept, *(wrap_system_reminder(item.text) for item in missing), *last_words]
        )
        _record_reminders(
            message.additional_properties,
            [*_recorded_reminders(message.additional_properties), *missing],
        )
        return idx

    @staticmethod
    def _is_last_words_reminder_content(content: Any) -> bool:
        """Whether a content item is a middleware-authored LAST_WORDS reminder.

        User-authored reminder tags are escaped during enrichment, so a raw
        wrapped ``[LAST_WORDS]`` block can only come from the LAST_WORDS state.
        """
        return (
            content.type == "text"
            and content.text is not None
            and content.text.startswith(f"{REMINDER_TAG_OPEN}\n{LAST_WORDS_PREFIX}")
        )

    def queue_hook_reminders(self, reminders: list[str], *, for_next_turn: bool = False) -> None:
        """Queue hook-provided reminders for the current or next user turn."""
        clean = [r for r in reminders if r]
        if not clean:
            return
        state = None if for_next_turn else self._turns.current()
        if state is not None:
            state.event_reminders = (*state.event_reminders, *clean)
            return
        self._pending_hook_reminders.extend(clean)

    def queue_drained_injection_reminders(self, reminders: list[str]) -> None:
        """Queue a drained injection's hook/skill reminders for the call that sends it.

        The injection middleware runs before this one in the same call, so
        they land on the injected message; an injection that never reaches a
        call (cancelled, or returned to the input box) never queues them.
        """
        clean = [reminder for reminder in reminders if reminder]
        if clean:
            state = self._turns.ensure()
            state.event_reminders = (*state.event_reminders, *clean)

    def update_skill_catalog_for_active_turn(self) -> None:
        """Refresh the active turn's skill-catalog reminder from the provider."""
        state = self._turns.current()
        if state is None:
            return
        state.skill_catalog = self._sources.skills.snapshot()

    async def refresh_extension_context(self, prompt: str, *, keep: bool = False) -> tuple[Warning, ...]:
        """Ask the agent's extension contexts for the prepared turn's text; the failures to report come back.

        *prompt* is what the turn was asked to do. With *keep*, a turn that
        already has their text keeps it: a retry that preserved the turn's
        reminders sends the same text, and asks only when nothing was kept
        (the first retry after a restart). Without a prepared turn this does
        nothing.

        A task that did not inherit the prepared turn (a workflow node's pass
        the user retried from another task) takes it on here, so the model
        calls it starts send the text it stores.
        """
        state = self._turns.current()
        if state is None:
            return ()
        if self._turns.local() is None:
            self._turns.install_local(state)
        if keep and state.extension_catalogs is not None:
            return ()
        catalogs, warnings = await self._sources.extension_context.collect(prompt)
        state.extension_catalogs = catalogs
        return warnings

