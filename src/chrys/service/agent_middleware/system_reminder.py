    # ChatMiddleware interface
    # ------------------------------------------------------------------

    async def process(
        self,
        context: ChatContext,
        call_next: Callable[[], Awaitable[None]],
    ) -> None:
        reminder_items = self._build_reminder_items()
        last_words_reminders = self._last_words_reminders()
        applied_switch: SwitchSnapshot | None = None
        # Replace user messages in the per-call shallow copy only.  This
        # renders recorded reminders and defangs user-authored reminder tags
        # without modifying the tool loop's prepped_messages or
        # SessionContext.input_messages.  Tool-result messages are
        # intentionally not escaped here.
        # ``ChatMiddlewareLayer`` always gives ``ChatContext`` a fresh mutable
        # list; the kernel constructor's public annotation is the broader
        # ``Sequence`` accepted at its external boundary.
        messages = cast("list[Message]", context.messages)
        target, target_idx = self._find_user_message(messages)
        if target is not None and (not _is_visible(target) or _is_continuation_poll(context)):
            # An excluded message never reaches the wire, and a poll's
            # messages are ignored: recording on either would claim a
            # delivery that never happened.
            target, target_idx = None, -1
        records = self._rendered_records(messages)
        handle = _service_handle(context.options.get("conversation_id") if context.options is not None else None)
        held = self._held_catalogs[1] if self._held_catalogs is not None and self._held_catalogs[0] == handle else {}
        in_view = {**held, **_latest_visible_catalogs(messages, records)}
        turn_recorded = self._turn_recorded(messages, records, target_idx) if target is not None else []
        new_items = self._unsent_reminders(in_view, turn_recorded, reminder_items) if target is not None else []
        for msg_idx, message in enumerate(messages):
            if message.role != "user" or not _is_visible(message):
                # Excluded messages never reach the wire; nothing to render.
                continue
            reminders = [item.text for item in records[msg_idx]]
            message_last_words_reminders: list[str] = []
            if msg_idx == target_idx:
                reminders.extend(item.text for item in new_items)
                message_last_words_reminders = last_words_reminders
            if reminders or message_last_words_reminders or self._has_system_reminder_tags(message):
                messages[msg_idx] = self._create_enriched(message, reminders, message_last_words_reminders)
        if target is not None:
            if new_items:
                context.request_message_observers.append(
                    self._record_on_delivery(target.additional_properties, tuple(new_items))
                )
            state = self._turns.current()
            if state is not None and any(
                item.kind == "event" and item.text == state.context_warning for item in new_items
            ):
                context.request_message_observers.append(self._sources.context_warning.delivered)
            if state is not None and state.file_change is not None:
                # Delivered means an established provider request, not
                # a completed middleware chain: lazy streaming inner
                # middleware returns a proxy from call_next() and only
                # reaches the final handler at first stream
                # consumption. Observers run immediately before every
                # final-handler invocation, so a run cancelled before
                # consumption keeps the notice requeueable.
                context.request_message_observers.append(state.file_change.mark_delivered)
            if (
                state is not None
                and state.switch is not None
                and _latest_switch_notice((*turn_recorded, *new_items)) == state.switch.notice
            ):
                # Only a switch whose notice is the latest this request
                # carries (sent now or earlier in the turn) is consumed.
                applied_switch = state.switch

        polled = _is_continuation_poll(context)
        if not polled:
            # Unknown until this call is answered: a failed call may or may
            # not have left its catalogs in the conversation.
            self._held_catalogs = None
        await call_next()
        if not polled:
            carried = in_view | {_catalog_key(item): item.text for item in new_items if item.kind == "catalog"}
            self._hold_catalogs_on_answer(context, carried)
        if applied_switch is not None:
            self._sources.profile_switch.carried(applied_switch)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _build_reminders(self) -> list[str]:
        """Every reminder text this turn offers, whether or not already sent."""
        return [item.text for item in self._build_reminder_items()]

    def _build_reminder_items(self) -> list[_ReminderItem]:
        state = self._turns.local()
        if state is None:
            # Fallback for direct middleware use without ``prepare_turn()``.
            # It deliberately avoids consuming pending profile switches:
            # switch reminders are turn-scoped and must be snapshotted by
            # the caller that starts the turn.
            state = self._snapshot_turn_reminders(usage={}, include_pending_switch=False)
            state.skill_catalog = self._sources.skills.snapshot()
            state.mcp_instructions = self._sources.mcp.snapshot()
            self._turns.install_local(state)
        return self._compose_items(state)

    def _compose_items(self, state: TurnReminderState) -> list[_ReminderItem]:
        """Every reminder *state* offers, in send order, each with the kind that decides its re-send.

        The one place the send order is written: the turn line, the
        context-usage warning, the profile-switch notice, the event inbox in
        queue order, the workspace file change, then the catalogs in their
        fixed order.  ``_unsent_reminders`` keeps this order and appends the
        withdrawals; LAST_WORDS blocks go after everything, unrecorded.
        """
        items = [_ReminderItem("turn", text) for text in state.turn_reminders]
        if state.context_warning:
            items.append(_ReminderItem("event", state.context_warning))
        if state.switch is not None:
            items.append(_ReminderItem("switch", state.switch.notice))
        items.extend(_ReminderItem("event", text) for text in state.event_reminders)
        if state.file_change is not None:
            items.append(_ReminderItem("event", state.file_change.text))
        items.extend(self._catalog_items(state))
        return items

    def _catalog_items(self, state: TurnReminderState) -> list[_ReminderItem]:
        """The standing context this turn offers, one item per catalog name."""
        return [
            _ReminderItem("catalog", text, name)
            for name, text in (
                (self._sources.runtime_env.name, state.runtime_hint),
                (self._sources.sub_agents.name, state.sub_agent_tip),
                (self._sources.todo.name, state.todo),
                (self._sources.background_tasks.name, state.background_tasks),
                (self._sources.skills.name, state.skill_catalog),
                (self._sources.mcp.name, state.mcp_instructions),
                *(state.extension_catalogs or ()),
                (self._sources.archive_pointer.name, self._sources.archive_pointer.current_text()),
            )
            if text
        ]

    @staticmethod
    def _turn_recorded(
        messages: list[Message],
        records: list[list[_ReminderItem]],
        target_idx: int,
    ) -> list[_ReminderItem]:
        """Reminders recorded on the current turn's user messages still in view.

        Messages a fold excluded (or left out of the list entirely) no longer
        show theirs.  The current turn runs from its opener to the last user
        message, injected and resumed messages included; with no opener in
        the list, from its start.
        """
        turn_start = next((i for i in range(target_idx, -1, -1) if opens_turn(messages[i])), 0)
        return [
            item
            for idx in range(turn_start, target_idx + 1)
            if messages[idx].role == "user" and _is_visible(messages[idx])
            for item in records[idx]
        ]

    def _unsent_reminders(
        self,
        catalogs_in_view: Mapping[str, str],
        turn_recorded: list[_ReminderItem],
        items: list[_ReminderItem],
    ) -> list[_ReminderItem]:
        """Return the reminders the last user message still has to carry.

        Only reminders in view count as sent: *turn_recorded* for turn, event
        and switch reminders, *catalogs_in_view* (the latest version of each)
        for catalogs.
        """
        turn_started = any(item.kind == "turn" for item in turn_recorded)
        turn_texts = {item.text for item in turn_recorded}
        latest_switch = _latest_switch_notice(turn_recorded)
        catalogs = _catalog_updates(
            catalogs_in_view,
            [item for item in items if item.kind == "catalog"],
            self._withdrawn_notices,
        )
        unsent: list[_ReminderItem] = []
        for item in items:
            if item.kind == "turn":
                sent = turn_started
            elif item.kind == "switch":
                # Switches compare with the turn's latest one only: switching
                # Code → QA → Code → QA across retries repeats an earlier text.
                sent = latest_switch == item.text
                latest_switch = item.text
            elif item.kind == "event":
                # Two hooks can queue the same text; it still goes once.
                sent = item.text in turn_texts
                turn_texts.add(item.text)
            else:
                sent = item not in catalogs
            if not sent:
                unsent.append(item)
        # Withdrawal notices for catalogs no longer offered go last.
        unsent.extend(item for item in catalogs if item not in items)
        return unsent

    def _rendered_records(self, messages: Sequence[Message]) -> list[list[_ReminderItem]]:
        """Each message's recorded reminders as this session renders them, parsed once per call."""
        return [[self._rendered(item) for item in items] for items in _records_of(messages)]

    def _rendered(self, item: _ReminderItem) -> _ReminderItem:
        """A recorded reminder as this session renders it.

        A recorded archive pointer names this session's catalog
        (``ArchivePointerSource.retarget``).  Comparisons read the rendered
        text too, so a forked or moved session does not send it again.
        """
        pointer = self._sources.archive_pointer
        is_pointer_kind = item.kind == "turn" or (item.kind == "catalog" and item.name == pointer.name)
        retargeted = pointer.retarget(item.text) if is_pointer_kind else None
        if retargeted is None:
            return item
        return replace(item, text=retargeted)

    def _hold_catalogs_on_answer(self, context: ChatContext, carried: dict[str, str]) -> None:
        """Remember *carried* under the handle the answer to this call returns."""

        def _hold(response: ChatResponse) -> ChatResponse:
            handle = _service_handle(response.conversation_id)
            self._held_catalogs = (handle, carried) if handle is not None else None
            return response

        result = context.result
        if isinstance(result, ChatResponse):
            _hold(result)
        elif result is not None:
            # A stream is answered once it finalizes.
            context.stream_result_hooks.append(_hold)

    @staticmethod
    def _record_on_delivery(
        properties: dict[str, Any],
        items: tuple[_ReminderItem, ...],
    ) -> Callable[[Sequence[Message]], None]:
        """Return a request observer that records *items* once a request carries them.

        Observers run before every final-handler invocation, and again with
        the prepared provider request; a resent request carries the same
        enriched list.  The record is appended once per enrichment.
        """
        recorded = False

        def _observe(_messages: Sequence[Message]) -> None:
            nonlocal recorded
            if recorded:
                return
            recorded = True
            _record_reminders(properties, [*_recorded_reminders(properties), *items])

        return _observe

    def _is_current_run_target_valid(self, target: CurrentRunReminderTarget) -> bool:
        if target.scope not in self._current_run_scopes:
            return False
        if target.phase == "prepared":
            return self._active_turn_scope is target.scope and self._turns.active is target.state
        if self._active_turn_scope is target.scope and self._turns.active is not None:
            return True
        return self._active_turn_scope is None and target.generation == self._current_run_reminder_generation

    def _snapshot_turn_reminders(
        self,
        *,
        usage: Mapping[str, Any],
        include_pending_switch: bool = True,
    ) -> TurnReminderState:
        """Snapshot the turn-level reminders, with the pending switch and its notice if included.

        The returned state holds the turn line, the context-usage warning,
        the standing runtime/sub-agent/todo context and the switch; the
        caller adds the rest.
        """
        state = TurnReminderState(
            runtime_hint=self._sources.runtime_env.snapshot(),
            sub_agent_tip=self._sources.sub_agents.snapshot(),
            todo=self._sources.todo.snapshot(),
            background_tasks=self._sources.background_tasks.snapshot(),
        )

        # The turn line: time at turn start and the previous turn's usage.
        turn_line = self._sources.turn_line.snapshot(usage)
        state.context_warning = self._sources.context_warning.snapshot(usage)
        if turn_line is not None:
            state.turn_reminders = (turn_line,)

        # Profile switch (stable for this turn; sent as an event)
        if include_pending_switch:
            state.switch = self._sources.profile_switch.snapshot()

        return state

    def _last_words_reminders(self) -> list[str]:
        """The LAST_WORDS blocks this call appends after every other reminder."""
        return self._last_words.render() if self._last_words is not None else []

    @staticmethod
    def _find_user_message(messages: list[Any]) -> tuple[Message | None, int]:
        """Return the last user ``Message`` and its index, or ``(None, -1)``."""
        for i in range(len(messages) - 1, -1, -1):
            if messages[i].role == "user":
                return messages[i], i
        return None, -1

    @staticmethod
    def _has_system_reminder_tags(message: Message) -> bool:
        """Return true if a message contains raw reserved reminder tags."""
        for c in message.contents:
            if (
                c.type == "text"
                and c.text is not None
                and (REMINDER_TAG_OPEN in c.text or REMINDER_TAG_CLOSE in c.text)
            ):
                return True
        return False

    @classmethod
    def _create_enriched(
        cls,
        original: Message,
        turn_reminders: list[str],
        last_words_reminders: list[str],
    ) -> Message:
        """Create a new ``Message`` with user contents first and reminders last.

        This keeps the user's message as the first content item while leaving
        platform context close to the end of the message.
        """
        reminder_contents = [wrap_system_reminder(r) for r in [*turn_reminders, *last_words_reminders]]
        # Extract text from Content objects so Message() can rebuild them.
        # Non-text Content (images, etc.) is passed through as-is.
        original_items: list[Any] = []
        for c in original.contents:
            if c.type == "text" and c.text is not None:
                original_items.append(escape_system_reminder_tags(c.text))
            else:
                original_items.append(c)
        return cls._rebuild(original, [*original_items, *reminder_contents])

    @staticmethod
    def _rebuild(original: Message, contents: list[Any]) -> Message:
        """A fresh wrapper for *contents* that keeps the original's identity fields.

        ``additional_properties`` is shared by reference — the sanctioned
        write-through channel for exclusion flags and the reminder record.
        """
        rebuilt = Message(
            original.role,
            contents,
            author_name=original.author_name,
            message_id=original.message_id,
        )
        rebuilt.additional_properties = original.additional_properties
        return rebuilt
